import * as React from "react"
import { cn } from "@/registry/lib/utils"
import { Popover, PopoverContent, PopoverTrigger } from "@/registry/ui/popover"
import { Thinking } from "@/registry/ui/thinking"

/** Inside an AISurface the label becomes Sofia (the Vita thinking orb), placed before the title. */
const InSurface = React.createContext(false)
/** Inside a primary-coloured container (a person's chat bubble, a selection bar) the label turns white. */
const OnPrimaryCtx = React.createContext(false)

/**
 * OnPrimary, wrap the content of a container painted in the primary colour (bg-primary) so every AILabel inside it
 * takes the white tone by itself. ChatBubble (the person's side) and the DataTable's selection bar already do.
 */
export function OnPrimary({ children }: { children: React.ReactNode }) {
  return <OnPrimaryCtx.Provider value={true}>{children}</OnPrimaryCtx.Provider>
}

/**
 * AILabel, marks content or controls GENERATED or AUTOFILLED by AI, and explains how.
 * Mandatory wherever AI produced a value the user may rely on. Clicking opens an explainability popover.
 * A pill: rainbow edge with plain text when standing alone; muted (hairline, low-opacity text) inside another
 * component; white (hairline and text in the primary's foreground) on a primary-coloured container, where grey
 * would sink into the blue. Inside an AISurface it is Sofia, the small thinking orb, and sits BEFORE the title.
 */
export function AILabel({ size = "md", children, title = "AI explained", className, onRevert, tone = "auto" }: {
  size?: "xs" | "sm" | "md"
  /** Explainability content: what the model did, confidence, source/model name. */
  children?: React.ReactNode
  title?: string
  className?: string
  /** When the AI changed a user value, offer a way back. */
  onRevert?: () => void
  /**
   * auto (default): rainbow when standing alone; muted inside another component (field, notification, tile, AI
   * surface, anything marked data-ai-context); white on a primary container (inside OnPrimary). Force with
   * spectrum | muted | on-primary.
   */
  tone?: "auto" | "spectrum" | "muted" | "on-primary"
}) {
  const s = { xs: "h-4 px-1 text-[0.625rem]", sm: "h-5 px-1.5 text-caption", md: "h-6 px-2 text-caption" }[size]
  const inSurface = React.useContext(InSurface)
  const inPrimary = React.useContext(OnPrimaryCtx)
  const onPrimary = tone === "on-primary" || (tone === "auto" && inPrimary)
  const explain = (
    <PopoverContent className="w-80 ai-gradient-border" caret>
      <p className="text-caption font-semibold"><span className="ai-gradient-text">AI</span></p>
      <p className="mt-1 text-headline">{title}</p>
      <div className="mt-2 text-body text-muted-foreground">{children ?? "This content was generated by AI. Review it before relying on it."}</div>
    </PopoverContent>
  )
  if (inSurface && tone === "auto") {
    return (
      <Popover>
        <PopoverTrigger aria-label="AI – Show information" className={cn("inline-flex shrink-0 rounded-full focus-ring", className)}>
          <Thinking mode="generating" size="sm" label="AI" />
        </PopoverTrigger>
        {explain}
      </Popover>
    )
  }
  return (
    <span className="inline-flex items-center gap-1">
      <Popover>
        <PopoverTrigger
          aria-label="AI – Show information"
          className={cn(
            "inline-flex items-center rounded-pill font-semibold tracking-wide text-foreground focus-ring",
            // The rainbow lives on the border; the text stays plain and readable.
            !onPrimary && tone !== "muted" && "ai-gradient-border",
            !onPrimary && tone === "auto" &&
              "in-data-[ai-context]:border in-data-[ai-context]:border-border-strong! in-data-[ai-context]:bg-none! in-data-[ai-context]:bg-transparent! in-data-[ai-context]:animate-none! in-data-[ai-context]:[&>span]:bg-none! in-data-[ai-context]:[&>span]:text-muted-foreground!",
            tone === "muted" && "border border-border-strong bg-none bg-transparent [&>span]:bg-none! [&>span]:text-muted-foreground!",
            // White: the primary's own foreground for the hairline and the letters, with the ring to match.
            onPrimary && "border border-primary-foreground/70 bg-transparent text-primary-foreground [--vita-ring:var(--vita-primary-foreground)]",
            s,
            className,
          )}
        >
          <span>AI</span>
        </PopoverTrigger>
        {explain}
      </Popover>
      {onRevert && (
        <button type="button" onClick={onRevert} className={cn("rounded-sm px-1 text-caption underline decoration-transparent hover:decoration-current focus-ring", onPrimary ? "text-primary-foreground" : "text-link")}>
          Revert to AI input
        </button>
      )}
    </span>
  )
}

/** AISurface, container treatment for AI-generated regions (tiles, table cells, fields). Labels inside go muted. */
export function AISurface({ className, ...props }: React.HTMLAttributes<HTMLDivElement>) {
  return (
    <InSurface.Provider value={true}>
      <div data-ai-context="" className={cn("scope-lg ai-gradient-border p-3", className)} {...props} />
    </InSurface.Provider>
  )
}
