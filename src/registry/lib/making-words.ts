/** The Creator-voice words, ready to rotate. */
export const makingWords: readonly string[] = makingWordPairs.map(([, w]) => w)

/** A random making word, optionally different from the current one. */
export function nextMakingWord(current?: string): string {
  if (makingWords.length < 2) return makingWords[0] ?? "Making"
  let w = current
  while (w === current) w = makingWords[Math.floor(Math.random() * makingWords.length)]
  return w as string
}
