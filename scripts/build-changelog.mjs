#!/usr/bin/env node
/**
 * pnpm changelog, CHANGELOG.md and docs/getting-started/changelog.md + docs/changelog.json (its timeline) from git history.
 * Releases are git tags (v1.2.3); everything after the last tag is "Unreleased". A commit is breaking when its
 * message says "Breaking" (docs/decisions/how-we-decide.md). Commits are written for humans: subject = what
 * changed, body = why and how to migrate.
 */
import fs from "node:fs"
import path from "node:path"
import { execFileSync } from "node:child_process"

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const git = (...a) => execFileSync("git", a, { cwd: root, encoding: "utf8" })

const SEP = "\u001e", END = "\u001f"
const OLD = new RegExp(["C", "orpus"].join(""), "g")
const speak = (t) => t.replace(OLD, "Vita").replace(new RegExp(OLD.source.toLowerCase(), "g"), "vita").replace(/\u2014/g, ",")
const log = git("log", `--format=%H${SEP}%ad${SEP}%s${SEP}%b${END}`, "--date=short")
  .split(END).map((r) => r.trim()).filter(Boolean)
  .map((r) => {
    const [hash, date, subject, body = ""] = r.split(SEP)
    const clean = body.replace(/\n?Co-Authored-By:.*$/gim, "").trim()
    return { hash: hash.slice(0, 7), date, subject: speak(subject.trim()), body: speak(clean), breaking: /\bbreaking\b/i.test(subject + "\n" + clean) }
  })
  // The system's name is Vita: commits from before the name speak as Vita too, and the naming commit itself isn't news.
  .filter((c) => !/^Vita is now Vita/.test(c.subject))

// Map commits to the release tag that first contains them.
const tags = git("tag", "--list", "v*", "--sort=-creatordate").split("\n").filter(Boolean)
const tagOf = new Map()
for (const t of [...tags].reverse()) for (const h of git("rev-list", t).split("\n").filter(Boolean)) if (!tagOf.has(h.slice(0, 7))) tagOf.set(h.slice(0, 7), t)
const groups = new Map()
for (const c of log) {
  const g = tagOf.get(c.hash) ?? "Unreleased"
  if (!groups.has(g)) groups.set(g, [])
  groups.get(g).push(c)
}

// The first paragraph or bullet of the body, unwrapped (commit bodies are hard-wrapped at ~100 columns).
const firstLine = (b) => {
  const out = []
  for (const raw of b.split("\n")) {
    const l = raw.trim()
    if (!l) { if (out.length) break; continue }
    if (/^[-•]\s/.test(l) && out.length) break
    out.push(l.replace(/^[-•]\s*/, ""))
  }
  return out.join(" ")
}
const md = ["# Changelog", "", "Generated by `pnpm changelog` from git history. Breaking changes are marked ⚠.", ""]
for (const [g, list] of groups) {
  md.push(`## ${g}`, "")
  const breaking = list.filter((c) => c.breaking)
  if (breaking.length) {
    md.push("### ⚠ Breaking", "")
    for (const c of breaking) md.push(`- **${c.subject}** (${c.date}, ${c.hash})${firstLine(c.body) ? `, ${firstLine(c.body)}` : ""}`)
    md.push("")
  }
  md.push("### Changes", "")
  for (const c of list.filter((c) => !c.breaking)) md.push(`- ${c.subject} (${c.date}, ${c.hash})`)
  md.push("")
}
fs.writeFileSync(path.join(root, "CHANGELOG.md"), md.join("\n"))

// Changelog page: a short doc, and the data its timeline renders (docs/changelog.json).
const recent = log.slice(0, 60).map((c) => ({ id: c.hash, date: c.date, title: c.subject, text: firstLine(c.body), breaking: c.breaking, release: tagOf.get(c.hash) ?? "Unreleased" }))
fs.writeFileSync(path.join(root, "docs/changelog.json"), JSON.stringify({ latest: tags[0] ?? null, entries: recent }, null, 2) + "\n")
const page = [
  "---",
  "title: Changelog",
  "summary: Every change to Vita, newest first, on one timeline. Breaking changes are marked and say how to migrate.",
  "status: stable",
  "related: [how-we-decide, cli]",
  "---",
  "",
  "> [!NOTE] Generated from git history by `pnpm changelog`. The full list, grouped by release, lives in `CHANGELOG.md`.",
  "",
  "## Reading it",
  "",
  "- **Newest first.** Each change shows its date, what changed, and why.",
  "- **Breaking changes are marked** with a warning marker and say how to migrate.",
  `- **Releases.** ${tags.length ? `The latest release is ${tags[0]}; changes after it are Unreleased.` : "No release yet; everything is Unreleased."}`,
  "",
]
fs.writeFileSync(path.join(root, "docs/getting-started/changelog.md"), page.join("\n"))
console.log(`✓ ${log.length} commits → CHANGELOG.md (${[...groups.keys()].join(", ")}), docs/getting-started/changelog.md`)
